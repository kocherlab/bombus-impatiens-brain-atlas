# Generators that read a results/ table another script writes: scan that script
# too (the producing step is not a registered predecessor).
PRODUCED_BY = {
    "scripts/kenyon/table_mb_ol_kc_labels.py": [
        "scripts/kenyon/project_kc_populations_with_optic.py"
    ],
}


def sibling_modules(path: Path) -> list[Path]:
    """scripts/ modules ``path`` imports (one level)."""
    try:
        tree = ast.parse(path.read_text(errors="replace"))
    except SyntaxError:
        return []
    out = []
    for n in ast.walk(tree):
        names = []
        if isinstance(n, ast.ImportFrom) and n.module and not n.level:
            names = [n.module]
        elif isinstance(n, ast.Import):
            names = [a.name for a in n.names]
        for m in names:
            rel = m.replace(".", "/") + ".py"
            for c in (REPO / "scripts" / rel, path.parent / rel):
                if c.is_file() and c != path and c not in out:
                    out.append(c)
    return out


def upstream(scripts: list[str]) -> list[str]:
    files = []
    for s in scripts:
        p = REPO / s
        if p.is_file():
            files += [p, *sibling_modules(p)]
    text = "\n".join(f.read_text(errors="replace") for f in files)
    return [label for rx, label in UPSTREAM if re.search(rx, text)]


def rows() -> list[tuple[str, ...]]:
    from paper import manuscript_figure_registry as reg

    def row(kind, slug, generator):
        steps = reg.predecessors(generator) if generator else []
        gen = f"`{generator}`" if generator else "(hand-written)"
        first = ", ".join(f"`{s}`" for s in steps) or ""
        scanned = [generator, *steps, *PRODUCED_BY.get(generator, [])]
        up = ", ".join(upstream(scanned)) if generator else ""
        return (kind, f"`{slug}`", DESCRIPTIONS[slug], gen, first, up)

    out = []
    for f in reg.FIGURES:
        kind = "Main figure" if f.kind == "main" else "Supp. figure"
        out.append(row(kind, f.slug, f.generator))
    for t in reg.TABLES:
        out.append(row("Supp. table", t.slug, t.generator))
    sd = "supplementary_data"
    out.append(row("Supp. Data", sd, reg.SUPPLEMENTARY_DATA_SCRIPT))
    return out


def render() -> str:
    head = ("Item", "Slug", "What it shows", "Made by", "Runs first", "Built on")
    lines = [
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows()]
    return "\n".join(lines)


def missing_descriptions() -> list[str]:
    from paper import manuscript_figure_registry as reg

    slugs = [f.slug for f in reg.FIGURES] + [t.slug for t in reg.TABLES]
    return [s for s in [*slugs, "supplementary_data"] if s not in DESCRIPTIONS]


def updated(readme: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise SystemExit(f"README.md needs one {START!r} and one {END!r} line")
    a = readme.index(START) + len(START)
    b = readme.index(END)
    return readme[:a] + "\n" + render() + "\n" + readme[b:]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if README is stale")
    a = ap.parse_args(argv)
    gaps = missing_descriptions()
    if gaps:
        print(f"no description in make_figure_map.DESCRIPTIONS for: {gaps}")
        return 1
    old = README.read_text()
    new = updated(old)
    if a.check:
        if new != old:
            print("README.md figure map is stale: run scripts/paper/make_figure_map.py")
            return 1
        print("README.md figure map is current")
        return 0
    if new != old:
        README.write_text(new)
        print("README.md figure map rewritten")
    return 0


if __name__ == "__main__":
    sys.path[:0] = [str(REPO / "scripts"), str(REPO / "src")]
    raise SystemExit(main())
